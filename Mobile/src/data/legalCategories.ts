export const getLegalCategory = (id: string) => LEGAL_CATEGORIES.find((item) => item.id === id);

export const getLegalSubCategory = (categoryId: string, subId: string) =>
  getLegalCategory(categoryId)?.subcategories.find((sub) => sub.id === subId);

/** References are `categoryId:subcategoryId`, e.g. `labour:salary-not-paid`. */
export const parseCombinableRef = (
  ref: string,
): { categoryId: LegalCategoryKey; subId: string } | null => {
  const sep = ref.indexOf(':');
  if (sep <= 0) return null;
  const categoryId = ref.slice(0, sep) as LegalCategoryKey;
  const subId = ref.slice(sep + 1);
  if (!subId || !LEGAL_CATEGORIES.some((c) => c.id === categoryId)) return null;
  return { categoryId, subId };
};

export const resolveCombinableTitle = (ref: string): string => {
  const p = parseCombinableRef(ref);
  if (!p) return ref;
  return getLegalSubCategory(p.categoryId, p.subId)?.title ?? ref;
};
